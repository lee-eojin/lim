const BROKEN = {
  DecideNextStopHasProof: (stop, ids) => `record stopped the loop as ${stop} while ${ids} had no regression test or no-test reason.`,
  StopIfProvenStopHasProof: (stop, ids) => `stopIfProven stopped the loop as ${stop} while ${ids} had no regression test or no-test reason.`,
  StopWaitingStopHasProof: (stop, ids) => `stopWaiting stopped the loop as ${stop} while ${ids} had no regression test or no-test reason.`,
  GateNeedsProof: (stop, ids) => `the commit gate lets a commit through (allow, or ask to confirm) while ${ids} has no regression test or no-test reason.`,
};

export function readConfig(text) {
  const constant = (name) => {
    const match = text.match(new RegExp(`^\\s*${name}\\s*=\\s*(\\d+)\\s*$`, 'm'));
    if (!match) throw new Error(`ReviewLoop.cfg has no ${name} = <number>`);
    return Number(match[1]);
  };
  const invariants = [...text.matchAll(/^INVARIANT\s+(\w+)\s*$/gm)].map((match) => match[1]);
  return { slots: constant('N'), maxRounds: constant('MaxRounds'), roundLimit: constant('RoundLimit'), invariants };
}

function countsFor(length, code, base) {
  return Array.from({ length }, (_, index) => Math.floor(code / base ** index) % base);
}

// Every input the model can hand decideNext, indexed as Rows[Len(counts)][CountsCode(counts) + 1][waiting + 1]
// [unproven + 1][stuck + 1][regressions + 1], so the spec's lookup is a plain function application.
export function decideNextModule(decideNext, { slots, maxRounds, roundLimit }) {
  const outcomes = [];
  const outcomeIndex = (result) => {
    if (!['stop', 'continue'].includes(result?.decision) || typeof result.reason !== 'string') {
      throw new Error(`decideNext returned ${JSON.stringify(result)}, expected { decision: 'stop' or 'continue', reason }`);
    }
    const key = `${result.decision}:${result.reason}`;
    if (!outcomes.includes(key)) outcomes.push(key);
    return outcomes.indexOf(key) + 1;
  };
  const range = (size) => Array.from({ length: size }, (_, index) => index);
  const tuple = (items) => `<<${items.join(', ')}>>`;
  const base = slots + 1;
  const rows = range(roundLimit).map((index) => {
    const length = index + 1;
    const lines = range(base ** length).map((code) => {
      const counts = countsFor(length, code, base);
      const byWaiting = range(base).map((waiting) => tuple(range(base).map((unproven) => tuple(range(base).map((stuck) => tuple([0, 1].map((regressions) => outcomeIndex(decideNext({
        round: length, maxRounds, counts, open: counts.at(-1), waiting, unproven,
        stuck: Array.from({ length: stuck }, () => ({})), regressions: Array.from({ length: regressions }, () => ({})),
      })))))))));
      return `    ${tuple(byWaiting)}`;
    });
    return `  <<\n${lines.join(',\n')}\n  >>`;
  });
  const outcomeRecords = outcomes.map((key) => {
    const [decision, reason] = key.split(':');
    return `[decision |-> "${decision}", reason |-> "${reason}"]`;
  });
  return [
    '---- MODULE DecideNextTable ----',
    '\\* Generated by scripts/check-loop-model.mjs from decideNext in loop.mjs. Do not edit.',
    'EXTENDS Naturals, Sequences',
    `TableSlots == ${slots}`,
    `TableMaxRounds == ${maxRounds}`,
    `TableRoundLimit == ${roundLimit}`,
    `Outcomes == ${tuple(outcomeRecords)}`,
    `Rows == <<\n${rows.join(',\n')}\n>>`,
    'RECURSIVE CountsCode(_)',
    `CountsCode(counts) == IF counts = <<>> THEN 0 ELSE Head(counts) + ${base} * CountsCode(Tail(counts))`,
    'DecideNext(counts, waiting, unproven, stuck, regressions) ==',
    '  Outcomes[Rows[Len(counts)][CountsCode(counts) + 1][waiting + 1][unproven + 1][stuck + 1][regressions + 1]]',
    '====',
    '',
  ].join('\n');
}

export function parseValue(text) {
  let index = 0;
  const skip = () => { while (/\s/.test(text[index] ?? '')) index += 1; };
  const expect = (token) => {
    skip();
    if (!text.startsWith(token, index)) throw new Error(`expected ${token} at ${index} in ${text.slice(index, index + 40)}`);
    index += token.length;
  };
  const list = (close, item) => {
    const items = [];
    skip();
    if (text.startsWith(close, index)) { index += close.length; return items; }
    for (;;) {
      items.push(item());
      skip();
      if (text.startsWith(close, index)) { index += close.length; return items; }
      expect(',');
    }
  };
  const value = () => {
    skip();
    if (text.startsWith('<<', index)) { index += 2; return list('>>', value); }
    if (text[index] === '{') { index += 1; return list('}', value); }
    if (text[index] === '[') {
      index += 1;
      return Object.fromEntries(list(']', () => {
        skip();
        const name = text.slice(index).match(/^\w+/)[0];
        index += name.length;
        expect('|->');
        return [name, value()];
      }));
    }
    if (text[index] === '(') {
      index += 1;
      const entries = [];
      for (;;) {
        const key = value();
        expect(':>');
        entries.push([key, value()]);
        skip();
        if (text[index] === ')') { index += 1; return Object.fromEntries(entries); }
        expect('@@');
      }
    }
    if (text[index] === '"') {
      const match = text.slice(index).match(/^"((?:[^"\\]|\\.)*)"/);
      index += match[0].length;
      return match[1].replace(/\\(.)/g, '$1');
    }
    const match = text.slice(index).match(/^(TRUE|FALSE|-?\d+)/);
    if (!match) throw new Error(`cannot read TLC value at ${text.slice(index, index + 40)}`);
    index += match[0].length;
    return match[0] === 'TRUE' ? true : match[0] === 'FALSE' ? false : Number(match[0]);
  };
  const result = value();
  skip();
  if (index !== text.length) throw new Error(`unread TLC output after the value: ${text.slice(index, index + 40)}`);
  return result;
}

export function parseTrace(output) {
  const start = output.indexOf('The behavior up to this point is:');
  if (start === -1) return [];
  const blocks = output.slice(start).split(/^State \d+: .*$/m).slice(1);
  return blocks.map((block) => {
    const body = block.split(/^\s*$/m).find((part) => part.trim()) ?? '';
    const variables = {};
    for (const part of body.split(/^\/\\ /m).filter((piece) => piece.trim())) {
      const [, name, valueText] = part.match(/^(\w+) = ([\s\S]*)$/);
      variables[name] = parseValue(valueText.trim());
    }
    return variables;
  });
}

const SHAPES = {
  checkFix: 'a failing check',
  reviewerFix: 'a P1 or P2 to fix',
  reviewerAsk: 'a P1 or P2 that needs your call',
  reviewerAskMultipleFixes: 'a P1 or P2 whose only question is which of several fixes',
};
const SHAPE_ORDER = ['checkFix', 'reviewerFix', 'reviewerAsk', 'reviewerAskMultipleFixes'];

function findingsOf(loop) {
  return Object.values(loop.findings);
}

function unprovenSlots(loop) {
  return findingsOf(loop).flatMap((finding, index) => (
    finding.where === 'resolved' && finding.kind === 'reviewer' && finding.regression === 'none' ? [index + 1] : []));
}

function where(loop) {
  if (loop.awaiting === 'decisions') return `the loop is stopped (${loop.stopReason})`;
  return {
    review: `round ${loop.round} waits for a review`, fix: 'the loop waits for a fix', proof: 'the loop waits for proof',
  }[loop.awaiting] ?? loop.awaiting;
}

// Turns a TLC trace into the loop commands that produce it, with ids assigned the way assignIds does.
export function describeTrace(trace, invariant) {
  const ids = new Map();
  let nextId = 1;
  const id = (slot) => ids.get(slot) ?? `slot ${slot}`;
  const named = (slots) => slots.map(id).join(', ');
  const steps = [];
  trace.forEach(({ cmd, loop }, index) => {
    if (index === 0) return;
    const before = trace[index - 1].loop;
    let text;
    if (cmd.name === 'start') {
      const flag = cmd.unattended ? 'start --unattended' : 'start';
      text = cmd.resume ? `${flag} (resumes the run)` : flag;
    } else if (cmd.name === 'record') {
      const reported = [...cmd.new].sort(([slotA, shapeA], [slotB, shapeB]) => (
        Math.sign(SHAPE_ORDER.indexOf(shapeA) > 1) - Math.sign(SHAPE_ORDER.indexOf(shapeB) > 1)
        || SHAPE_ORDER.indexOf(shapeA) - SHAPE_ORDER.indexOf(shapeB) || slotA - slotB));
      const fixFirst = reported.filter(([, shape]) => SHAPE_ORDER.indexOf(shape) <= 1);
      const asks = reported.filter(([, shape]) => SHAPE_ORDER.indexOf(shape) > 1);
      const resolved = named([...cmd.resolved]);
      for (const [slot] of [...fixFirst, ...asks]) ids.set(slot, `F-${nextId++}`);
      const parts = [];
      if (resolved) parts.push(`resolved ${resolved}`);
      if (reported.length) parts.push(`new ${[...fixFirst, ...asks].map(([slot, shape]) => `${id(slot)} (${SHAPES[shape]})`).join(', ')}`);
      if (cmd.regression) parts.push('one new finding repeats a resolved one');
      text = `record round ${cmd.round} with ${parts.join('; ') || 'no findings and nothing resolved'}`;
    } else if (cmd.name === 'next') {
      if (before.awaiting === 'proof' && loop.awaiting === 'decisions' && loop.stopReason !== 'integrity') {
        text = 'next, and the final checks pass';
      } else if (before.awaiting === 'proof' && loop.awaiting === 'proof') {
        text = 'next, and a check fails that a new regression test explains, so that test loses its proof';
      } else if (before.awaiting === 'proof') {
        text = 'next, and a check fails that no new test explains, so the loop goes back to fix';
      } else {
        text = 'next';
      }
      if (loop.stopReason === 'integrity') text += ', with a fix that weakens a test or check';
    } else if (cmd.name === 'rule') {
      text = {
        noTest: `rule --id ${id(cmd.slot)} --no-test "<reason>"`,
        test: `rule --id ${id(cmd.slot)} --draft <test> (the draft fails on the code before the fix)`,
        missed: `rule --id ${id(cmd.slot)} --draft <test> (the draft does not fail on the code before the fix)`,
        ruleDraft: `rule --id ${id(cmd.slot)} --draft <rule> (${id(cmd.slot)} is decided as a rule)`,
      }[cmd.outcome];
    } else if (cmd.name === 'decide') {
      text = `decide --id ${id(cmd.slot)} --choice ${cmd.choice}`;
    } else if (cmd.name === 'unattended') {
      text = `unattended ${cmd.on ? '--on' : '--off'}`;
    } else {
      text = cmd.name;
    }
    steps.push(`${index}. ${text}. Now ${where(loop)}.`);
  });
  const last = trace.at(-1).loop;
  const unproven = named(unprovenSlots(last));
  return [...steps, `Broken: ${BROKEN[invariant]?.(last.stopReason, unproven) ?? invariant}`];
}

function sha256(file) {
  return createHash('sha256').update(readFileSync(file)).digest('hex');
}

async function ensureJar() {
  if (existsSync(TLA_TOOLS.path) && sha256(TLA_TOOLS.path) === TLA_TOOLS.sha256) return TLA_TOOLS.path;
  mkdirSync(path.dirname(TLA_TOOLS.path), { recursive: true });
  console.log(`downloading ${TLA_TOOLS.url}`);
  const response = await fetch(TLA_TOOLS.url);
  if (!response.ok) throw new Error(`download failed: HTTP ${response.status}`);
  const partial = `${TLA_TOOLS.path}.part`;
  writeFileSync(partial, Buffer.from(await response.arrayBuffer()));
  const actual = sha256(partial);
  if (actual !== TLA_TOOLS.sha256) {
    rmSync(partial, { force: true });
    throw new Error(`tla2tools.jar has sha256 ${actual}, expected ${TLA_TOOLS.sha256}; nothing was kept`);
  }
  renameSync(partial, TLA_TOOLS.path);
  return TLA_TOOLS.path;
}

// Several workers make a full search fast; one worker keeps breadth-first order, so its counterexample is a shortest one.
function runTlc(jar, folder, config, workers) {
  return new Promise((resolve, reject) => {
    const args = [
      '-XX:+UseParallelGC', '-cp', jar, 'tlc2.TLC', '-config', config, '-deadlock', '-workers', String(workers),
      '-metadir', path.join(folder, 'states', `${path.basename(config, '.cfg')}-${workers}`), 'ReviewLoop',
    ];
    const tlc = spawn('java', args, { cwd: folder });
    let output = '';
    tlc.stdout.on('data', (chunk) => { output += chunk; });
    tlc.stderr.on('data', (chunk) => { output += chunk; });
    tlc.on('error', (error) => reject(new Error(`could not run java: ${error.message}. TLC needs Java 11 or later on PATH`)));
    tlc.on('close', (code) => resolve({ code, output }));
  });
}

function readOptions(args) {
  const options = { invariants: [] };
  for (let index = 0; index < args.length; index += 1) {
    if (args[index] === '--loop') options.loop = path.resolve(args[++index]);
    else if (args[index] === '--invariant') options.invariants.push(args[++index]);
    else throw new Error(`unknown argument ${args[index]}; use --loop <loop.mjs> and --invariant <name>`);
  }
  return options;
}

async function main() {
  const options = readOptions(process.argv.slice(2));
  const configText = readFileSync(path.join(modelFolder, 'ReviewLoop.cfg'), 'utf8');
  const bounds = readConfig(configText);
  const unknown = options.invariants.filter((name) => !bounds.invariants.includes(name));
  if (unknown.length) throw new Error(`no invariant ${unknown.join(', ')} in ReviewLoop.cfg`);
  const invariants = options.invariants.length ? options.invariants : bounds.invariants;
  const loopFile = options.loop ?? defaultLoop;
  const { decideNext } = await import(pathToFileURL(loopFile).href);
  if (typeof decideNext !== 'function') throw new Error(`${loopFile} does not export decideNext`);

  const jar = await ensureJar();
  const workFolder = mkdtempSync(path.join(tmpdir(), 'loop-model-'));
  copyFileSync(path.join(modelFolder, 'ReviewLoop.tla'), path.join(workFolder, 'ReviewLoop.tla'));
  writeFileSync(path.join(workFolder, 'DecideNextTable.tla'), decideNextModule(decideNext, bounds));
  const baseConfig = configText.replace(/^INVARIANT\s+\w+\s*$/gm, '').trimEnd();
  console.log(`decideNext from ${shown(loopFile)}; ${bounds.slots} findings, max ${bounds.maxRounds} rounds, rounds up to ${bounds.roundLimit}`);

  let results;
  try {
    results = await Promise.all(invariants.map(async (invariant) => {
      const config = path.join(workFolder, `${invariant}.cfg`);
      writeFileSync(config, `${baseConfig}\n\nINVARIANT RoundMatchesCounts\nINVARIANT ${invariant}\n`);
      const startedAt = Date.now();
      const workers = Math.max(1, Math.floor(availableParallelism() / invariants.length));
      let { output } = await runTlc(jar, workFolder, config, workers);
      if (workers > 1 && /^Error: Invariant \w+ is violated/m.test(output)) ({ output } = await runTlc(jar, workFolder, config, 1));
      return { invariant, output, seconds: ((Date.now() - startedAt) / 1000).toFixed(1) };
    }));
  } finally {
    rmSync(workFolder, { recursive: true, force: true });
  }
  let status = 0;
  for (const { invariant, output, seconds } of results) {
    const states = output.match(/^(\d+) states generated, (\d+) distinct states found/m);
    const size = states ? `${states[2]} distinct states` : 'no state count';
    const violated = output.match(/^Error: Invariant (\w+) is violated/m)?.[1];
    if (output.includes('Model checking completed. No error has been found.')) {
      console.log(`PASS ${invariant} (${size}, ${seconds} s)`);
    } else if (violated === invariant) {
      status = Math.max(status, 1);
      console.log(`FAIL ${invariant} (${seconds} s)`);
      for (const line of describeTrace(parseTrace(output), invariant)) console.log(`  ${line}`);
    } else {
      status = 2;
      console.log(`ERROR ${invariant}: TLC did not finish the check (modeling error or tool problem). TLC output:`);
      console.log(output.trim().split('\n').slice(-40).join('\n'));
    }
  }
  process.exit(status);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message);
    process.exit(2);
  });
}
